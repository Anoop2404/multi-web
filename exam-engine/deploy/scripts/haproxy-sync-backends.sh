#!/usr/bin/env bash
# LB_KIND=haproxy only: regenerate the HAProxy engine backend from the droplets tagged exam-engine.
set -euo pipefail
. "$(dirname "$0")/lib.sh"

usage() {
  cat <<'EOF'
Usage: haproxy-sync-backends.sh [--dry-run]

Writes /etc/haproxy/conf.d/50-engines.cfg on HAPROXY_HOST with one `server` line per droplet tagged
exam-engine (private IP, port 8090), validates the whole config (haproxy -c) and reloads HAProxy
(hitless). Called by scale-out.sh, scale-in.sh and rolling-update.sh when LB_KIND=haproxy.
See lb/haproxy/haproxy.cfg.

  --dry-run   print the generated backend instead of installing it
EOF
}
while (($#)); do
  case $1 in
    --dry-run) DRY_RUN=1; shift ;;
    -h|--help) usage; exit 0 ;;
    *) usage >&2; die "unknown argument $1" ;;
  esac
done

load_ops_env
require_cmd doctl jq ssh
[[ -n $HAPROXY_HOST ]] || die "HAPROXY_HOST is not set"

cfg=$(mktemp); trap 'rm -f "$cfg"' EXIT
{
  echo "# Generated by exam-engine/deploy/scripts/haproxy-sync-backends.sh at $(date -u +%FT%TZ). Do not edit."
  echo "backend engines"
  echo "    balance leastconn"
  echo "    option httpchk"
  echo "    http-check send meth GET uri /health ver HTTP/1.1 hdr Host exam-health"
  echo "    http-check expect status 200"
  echo "    http-reuse safe"
  echo "    default-server inter 3s fastinter 1s fall 3 rise 2 maxconn 30000 check"
  n=0
  while IFS=$'\t' read -r id name _pub priv _rest; do
    [[ -n ${id:-} && $priv != - ]] || continue
    echo "    server $name $priv:8090"
    n=$((n + 1))
  done <<<"$(droplets_by_tag "$ENGINE_LB_TAG" | sort -t$'\t' -k2,2)"
  (( n > 0 )) || echo "    # no engine nodes tagged $ENGINE_LB_TAG"
} > "$cfg"

if [[ $DRY_RUN == 1 ]]; then cat "$cfg"; exit 0; fi
grep -q '^    server ' "$cfg" || die "no engine nodes found -- refusing to install an empty backend"
ssh_node "$HAPROXY_HOST" 'sudo tee /etc/haproxy/conf.d/50-engines.cfg.new >/dev/null &&
  sudo cp -p /etc/haproxy/conf.d/50-engines.cfg /etc/haproxy/50-engines.cfg.bak 2>/dev/null;
  sudo mv /etc/haproxy/conf.d/50-engines.cfg.new /etc/haproxy/conf.d/50-engines.cfg &&
  if sudo haproxy -c -q -f /etc/haproxy/conf.d; then sudo systemctl reload haproxy; else
    echo "invalid config, restoring the previous backend" >&2;
    sudo cp -p /etc/haproxy/50-engines.cfg.bak /etc/haproxy/conf.d/50-engines.cfg; exit 1; fi' < "$cfg"
log "HAProxy backend updated: $(grep -c '^    server ' "$cfg") server(s)"
